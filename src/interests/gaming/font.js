/** Width in pixels of a string at scale s. */
export const textW = (str, s = 1) => str.length * 6 * s - s;

/** Draw text with an optional 1px drop shadow. `~` renders as ∞. */
export function text(ctx, str, x, y, color, s = 1, shadow = '#0d0f17') {
  const draw = (ox, oy, col) => {
    ctx.fillStyle = col;
    let cx = x + ox;
    for (const ch of str.toUpperCase()) {
      const g = G[ch] || G[' '];
      for (let r = 0; r < 7; r++) {
        const row = g[r];
        if (!row) continue;
        for (let c = 0; c < 5; c++) if (row & (16 >> c)) ctx.fillRect(cx + c * s, y + oy + r * s, s, s);
      }
      cx += 6 * s;
    }
  };
  if (shadow) draw(s, s, shadow);
  draw(0, 0, color);
}
